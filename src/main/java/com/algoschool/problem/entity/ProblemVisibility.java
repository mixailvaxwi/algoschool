package com.algoschool.problem.entity;

/**
 * Кому задача видна в банке.
 * <p>
 * Промежуточного значения «видна участникам курса» пока нет: курс не знает
 * своих соавторов и ассистентов — для этого нужна таблица членства, которая
 * появится вместе с группами. До тех пор задача либо личная, либо общая.
 */
public enum ProblemVisibility {
    /** Видна и доступна для вставки в урок только автору. */
    PRIVATE,
    /** Видна всем преподавателям; править и удалять по-прежнему может только автор. */
    PUBLIC
}
