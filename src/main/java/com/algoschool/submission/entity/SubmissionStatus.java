package com.algoschool.submission.entity;

public enum SubmissionStatus {
    PENDING,                // В очереди на проверку (важно для асинхронной проверки кода)

    /**
     * Ждёт человека, а не проверяющей системы: развёрнутый ответ проверяет
     * преподаватель (UC-T-40). Опрос Ejudge такие решения не подхватывает —
     * он смотрит только PENDING.
     */
    PENDING_REVIEW,

    CORRECT,                // Полностью верное решение (Accepted)

    /**
     * Часть ответа верна. Соответствие и упорядочивание считают долю верного,
     * и вердикт «неверно» при половине правильных пар вводил бы в заблуждение.
     * Шаг при этом непройденным остаётся: пройден — значит решён полностью.
     */
    PARTIALLY_CORRECT,

    WRONG_ANSWER,           // Неверный ответ (WA)
    COMPILATION_ERROR,      // Ошибка компиляции (CE)
    TIME_LIMIT_EXCEEDED,    // Превышен лимит времени (TLE)
    MEMORY_LIMIT_EXCEEDED,  // Превышен лимит памяти (MLE)
    RUNTIME_ERROR,          // Ошибка во время выполнения (RE)

    // Сбой инфраструктуры, а не вердикт: решение не удалось передать проверяющей
    // системе. Раньше в этом случае ставился RUNTIME_ERROR, и студент видел
    // «ошибка выполнения» вместо «проверяющая система недоступна».
    SUBMISSION_FAILED;

    /** Балла ещё нет: проверка не закончена и в политику зачёта не идёт. */
    public boolean isAwaitingCheck() {
        return this == PENDING || this == PENDING_REVIEW;
    }
}
